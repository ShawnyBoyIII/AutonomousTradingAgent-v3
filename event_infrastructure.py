@dataclass(slots=True, frozen=True)
class Event:
    """
    Abstract base class for all events.

    Time complexity: O(1) for instantiation.
    Memory overhead: Very low (~48 bytes) due to slots=True and frozen=True.
    """
    timestamp: int  # UTC nanoseconds

    def __post_init__(self) -> None:
        if not isinstance(self.timestamp, int) or self.timestamp < 0:
            raise EventValidationError("timestamp must be a non-negative integer (UTC nanoseconds).")

@dataclass(slots=True, frozen=True)
class MarketEvent(Event):
    """
    Market data event for ticks or bars.

    Time complexity: O(1)
    Memory overhead: ~120 bytes per instance.
    """
    symbol: str
    open: float
    high: float
    low: float
    close: float
    volume: float
    bid_ask_spread: float
    bar_type: BarType

    def __post_init__(self) -> None:
        Event.__post_init__(self)
        if not self.symbol:
            raise EventValidationError("symbol must not be empty.")
        if self.high < self.low:
            raise EventValidationError("high cannot be less than low.")
        if self.volume < 0:
            raise EventValidationError("volume cannot be negative.")
        if self.bid_ask_spread < 0:
            raise EventValidationError("bid_ask_spread cannot be negative.")

@dataclass(slots=True, frozen=True)
class SignalEvent(Event):
    """
    Trading signal event generated by strategies.

    Time complexity: O(1)
    Memory overhead: ~104 bytes per instance.
    """
    symbol: str
    signal_type: SignalDirection
    strength: float
    target_quantity: int
    suggested_stop_loss: Optional[float] = None
    suggested_take_profit: Optional[float] = None

    def __post_init__(self) -> None:
        Event.__post_init__(self)
        if not self.symbol:
            raise EventValidationError("symbol must not be empty.")
        if not isinstance(self.signal_type, SignalDirection):
            raise EventValidationError("signal_type must be a SignalDirection.")
        if not (0.0 <= self.strength <= 1.0):
            raise EventValidationError("strength must be between 0.0 and 1.0.")
        if self.target_quantity < 0:
            raise EventValidationError("target_quantity cannot be negative.")
        if self.suggested_stop_loss is not None and self.suggested_stop_loss < 0:
            raise EventValidationError("suggested_stop_loss cannot be negative.")
        if self.suggested_take_profit is not None and self.suggested_take_profit < 0:
            raise EventValidationError("suggested_take_profit cannot be negative.")

@dataclass(slots=True, frozen=True)
class OrderEvent(Event):
    """
    Order execution intent event.

    Time complexity: O(1)
    Memory overhead: ~120 bytes per instance.
    """
    symbol: str
    order_type: OrderType
    direction: OrderDirection
    quantity: int
    order_id: str
    limit_price: Optional[float] = None
    stop_price: Optional[float] = None
    time_in_force: TimeInForce = TimeInForce.GTC

    def __post_init__(self) -> None:
        Event.__post_init__(self)
        if not self.symbol:
            raise EventValidationError("symbol must not be empty.")
        if not self.order_id:
            raise EventValidationError("order_id must not be empty.")
        if not isinstance(self.order_type, OrderType):
            raise EventValidationError("order_type must be an OrderType.")
        if not isinstance(self.direction, OrderDirection):
            raise EventValidationError("direction must be an OrderDirection.")
        if self.quantity <= 0:
            raise EventValidationError("quantity must be positive.")
        if self.order_type == OrderType.LIMIT and self.limit_price is None:
            raise EventValidationError("LIMIT orders require a limit_price.")
        if self.order_type == OrderType.STOP and self.stop_price is None:
            raise EventValidationError("STOP orders require a stop_price.")
        if self.limit_price is not None and self.limit_price < 0:
            raise EventValidationError("limit_price cannot be negative.")
        if self.stop_price is not None and self.stop_price < 0:
            raise EventValidationError("stop_price cannot be negative.")

@dataclass(slots=True, frozen=True)
class FillEvent(Event):
    """
    Execution confirmation event.

    Time complexity: O(1)
    Memory overhead: ~136 bytes per instance.
    """
    symbol: str
    exchange: str
    quantity_filled: int
    fill_price: float
    direction: OrderDirection
    commission_fee: float
    slippage_cost: float
    impact_cost: float
    order_id: str

    def __post_init__(self) -> None:
        Event.__post_init__(self)
        if not self.symbol:
            raise EventValidationError("symbol must not be empty.")
        if not self.exchange:
            raise EventValidationError("exchange must not be empty.")
        if not self.order_id:
            raise EventValidationError("order_id must not be empty.")
        if not isinstance(self.direction, OrderDirection):
            raise EventValidationError("direction must be an OrderDirection.")
        if self.quantity_filled < 0:
            raise EventValidationError("quantity_filled cannot be negative.")
        if self.fill_price < 0:
            raise EventValidationError("fill_price cannot be negative.")
        if self.commission_fee < 0:
            raise EventValidationError("commission_fee cannot be negative.")
        if self.slippage_cost < 0:
            raise EventValidationError("slippage_cost cannot be negative.")
        if self.impact_cost < 0:
            raise EventValidationError("impact_cost cannot be negative.")


# =============================================================================
# Event Queue Infrastructure
# =============================================================================

@dataclass(order=True)
class _QueueItem:
    """Internal wrapper for priority queue ordering."""
    timestamp: int
    seqno: int
    event: Event = field(compare=False)

class EventQueue:
    """
    Thread-safe, priority-aware queue for Event objects.
    Ensures that events are processed strictly in temporal order (by timestamp).

    Time complexity:
    - put(): O(log N) due to heap push
    - get(): O(log N) due to heap pop
    """
    def __init__(self) -> None:
        self._queue: "queue.PriorityQueue[_QueueItem]" = queue.PriorityQueue()
        self._seq = itertools.count()
        self._last_timestamp: Optional[int] = None
        self._known_order_ids: set[str] = set()
        self._lock = threading.RLock()

    def put(self, event: Event) -> None:
        """
        Puts an event onto the queue.
        Validates temporal sequencing and raises an error if an event is older than
        the most recently processed event.
        Also validates that order_ids are unique.
        """
        if not isinstance(event, Event):
            raise EventValidationError(f"Expected an Event subclass, got {type(event).__name__}")

        with self._lock:
            # Temporal sequence validation against dequeued events
            if self._last_timestamp is not None and event.timestamp < self._last_timestamp:
                raise TemporalSequenceViolationError(
                    f"Event timestamp {event.timestamp} is older than the last "
                    f"processed timestamp {self._last_timestamp}."
                )

            # Duplicate order ID validation
            if isinstance(event, OrderEvent):
                if event.order_id in self._known_order_ids:
                    raise DuplicateOrderIdError(
                        f"Order ID {event.order_id} has already been queued."
                    )
                self._known_order_ids.add(event.order_id)

            item = _QueueItem(
                timestamp=event.timestamp,
                seqno=next(self._seq),
                event=event
            )
            self._queue.put(item)

    def get(self, timeout: Optional[float] = None) -> Event:
        """
        Retrieves the next event from the queue.
        Raises QueueStarvationError if no events are available within the timeout.
        """
        try:
            item = self._queue.get(timeout=timeout)
        except queue.Empty:
            raise QueueStarvationError("No events available in the queue.")

        with self._lock:
            # Re-verify temporal sequencing against dequeued events
            if self._last_timestamp is not None and item.event.timestamp < self._last_timestamp:
                raise TemporalSequenceViolationError(
                    f"Dequeued event timestamp {item.event.timestamp} is older than "
                    f"last processed timestamp {self._last_timestamp}."
                )
            self._last_timestamp = item.event.timestamp

        return item.event

    def empty(self) -> bool:
        """Returns True if the queue is empty, False otherwise."""
        return self._queue.empty()

    def qsize(self) -> int:
        """Returns the approximate size of the queue."""
        return self._queue.qsize()

