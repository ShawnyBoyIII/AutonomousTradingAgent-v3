# =============================================================================
# Exceptions
# =============================================================================

class EventEngineError(Exception):
    """Base class for all Event Engine exceptions."""
    pass

class QueueStarvationError(EventEngineError):
    """Raised when the event queue starves (no events available within timeout)."""
    pass

class EventValidationError(EventEngineError):
    """Raised when an event fails validation during instantiation."""
    pass

class TemporalSequenceViolationError(EventEngineError):
    """Raised when a historical event arrives out-of-order temporally."""
    pass

class DuplicateOrderIdError(EventValidationError):
    """Raised when an order with an already seen ID is submitted."""
    pass


