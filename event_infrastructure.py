def test_event_queue_temporal_ordering():
    eq = EventQueue()

    # Create events out of chronological order
    event1 = MarketEvent(100, "AAPL", 1.0, 1.0, 1.0, 1.0, 100, 0.01, BarType.TICK)
    event3 = MarketEvent(300, "AAPL", 1.0, 1.0, 1.0, 1.0, 100, 0.01, BarType.TICK)
    event2 = MarketEvent(200, "AAPL", 1.0, 1.0, 1.0, 1.0, 100, 0.01, BarType.TICK)

    # Enqueue them
    eq.put(event3)
    eq.put(event1)
    eq.put(event2)

    # They should come out in strict chronological order
    assert eq.get().timestamp == 100
    assert eq.get().timestamp == 200
    assert eq.get().timestamp == 300

def test_event_queue_temporal_violation():
    eq = EventQueue()

    event2 = MarketEvent(200, "AAPL", 1.0, 1.0, 1.0, 1.0, 100, 0.01, BarType.TICK)
    event1 = MarketEvent(100, "AAPL", 1.0, 1.0, 1.0, 1.0, 100, 0.01, BarType.TICK)

    eq.put(event2)
    # Process event2, advancing the queue's internal clock to 200
    eq.get()

    # Now trying to put event1 (timestamp 100) should raise a violation
    with pytest.raises(TemporalSequenceViolationError):
        eq.put(event1)

def test_event_queue_duplicate_order_id():
    eq = EventQueue()
    order1 = OrderEvent(
        timestamp=100, symbol="AAPL", order_type=OrderType.MARKET,
        direction=OrderDirection.BUY, quantity=10, order_id="ID1"
    )
    order2 = OrderEvent(
        timestamp=200, symbol="AAPL", order_type=OrderType.MARKET,
        direction=OrderDirection.BUY, quantity=20, order_id="ID1"
    )

    eq.put(order1)
    with pytest.raises(DuplicateOrderIdError):
        eq.put(order2)

def test_event_queue_starvation():
    eq = EventQueue()
    with pytest.raises(QueueStarvationError):
        eq.get(timeout=0.01)

