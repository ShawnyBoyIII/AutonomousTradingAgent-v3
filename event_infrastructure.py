import pytest

def test_market_event_validation():
    # Valid MarketEvent
    event = MarketEvent(
        timestamp=1625097600000000000,
        symbol="AAPL",
        open=150.0,
        high=152.0,
        low=149.0,
        close=151.0,
        volume=1000.0,
        bid_ask_spread=0.01,
        bar_type=BarType.TICK
    )
    assert event.symbol == "AAPL"

    # Invalid: negative volume
    with pytest.raises(EventValidationError):
        MarketEvent(
            timestamp=1625097600000000000,
            symbol="AAPL",
            open=150.0,
            high=152.0,
            low=149.0,
            close=151.0,
            volume=-10.0,
            bid_ask_spread=0.01,
            bar_type=BarType.TICK
        )

